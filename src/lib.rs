/// Derives `PartialEq`, `Eq` and `Hash` for a property type so that it can hold floats and
/// still be indexed. Floats compare by value, with `-0.0` equal to `0.0` and `NaN` equal to
/// itself; other fields use their own `Eq` and `Hash`.
///
/// ```rust
/// # use ixa::{define_entity, impl_property, EqHash};
/// # define_entity!(Person);
/// #[derive(Debug, Clone, Copy, EqHash, serde::Serialize, serde::Deserialize)]
/// pub enum Treatment {
///     Untreated,
///     Antiviral { dose_mg: f64 },
/// }
/// impl_property!(Treatment, Person, default_const = Treatment::Untreated);
/// ```
///
/// Limits:
/// - No generic types, unions or `#[repr(packed)]` structs.
/// - A tuple or array field cannot mix floats with non-primitive types: use separate fields.
/// - A value equal to the property's default is not stored, so `-0.0` set against a `0.0`
///   default can read back as `0.0`.
/// - If ixa is renamed or re-exported, add `#[eq_hash(crate = path::to::ixa)]`.
